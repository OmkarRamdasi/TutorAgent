def agent(question):
    """
    Main Agentic AI entry point.

    The agent:
    1. Understands the student's intention.
    2. Selects the appropriate capability.
    3. Executes it.
    """

    intent_result = detect_intent(
        question
    )

    if intent_result is None:
        return

    intent = intent_result.intent
    concept = intent_result.concept

    print("\n🤖 AGENT")
    print(
        f"Intent: {intent}"
    )

    if concept:

        print(
            f"Concept: {concept}"
        )

    # --------------------------------------------------------
    # TEACH
    # --------------------------------------------------------

    if intent == "teach":

        teach(question)

    # --------------------------------------------------------
    # PRACTICE
    # --------------------------------------------------------

    elif intent == "practice":

        if not concept:

            print(
                "\nPlease tell me which concept "
                "you want to practice."
            )

            return

        practice(
            concept
        )

    # --------------------------------------------------------
    # PROGRESS
    # --------------------------------------------------------

    elif intent == "progress":

        get_progress_report()

    else:

        print(
            "\nI couldn't determine what you want to do."
        )


