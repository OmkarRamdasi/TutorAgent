PROGRESS_FILE = Path("progress.json")


def load_progress():
    """
    Load the student's learning progress from disk.
    """

    if not PROGRESS_FILE.exists():
        return {}

    with open(
        PROGRESS_FILE,
        "r",
        encoding="utf-8"
    ) as file:

        return json.load(file)


def save_progress(progress):
    """
    Save the student's learning progress to disk.
    """

    with open(
        PROGRESS_FILE,
        "w",
        encoding="utf-8"
    ) as file:

        json.dump(
            progress,
            file,
            indent=4
        )


def get_concept_history(topic, concept):
    """
    Read the student's previous learning history
    for a specific topic and concept.
    """

    progress = load_progress()

    if topic not in progress:
        return None

    if concept not in progress[topic]:
        return None

    return progress[topic][concept]


def calculate_mastery(topic, concept):
    """
    Calculate the student's mastery percentage
    for a specific concept.
    """

    history = get_concept_history(
        topic,
        concept
    )

    if history is None:
        return 0.0

    attempts = history["attempts"]

    if attempts == 0:
        return 0.0

    correct = history["correct"]

    mastery = correct / attempts

    return mastery


def get_learning_state(mastery):
    """
    Convert mastery score into a simple learning state.
    """

    if mastery < 0.5:
        return "weak"

    elif mastery < 0.8:
        return "learning"

    else:
        return "strong"


def get_progress_report():
    """
    Generate a learning progress report
    from the student's saved memory.
    """

    progress = load_progress()

    if not progress:

        print(
            "\n📊 No learning progress yet."
        )

        return

    print("\n" + "=" * 60)
    print("📊 YOUR DATA SCIENCE PROGRESS")
    print("=" * 60)

    total_concepts = 0
    strong_concepts = 0
    learning_concepts = 0
    weak_concepts = 0

    for topic, concepts in progress.items():

        print(f"\n📚 {topic}")
        print("-" * 60)

        for concept, data in concepts.items():

            total_concepts += 1

            attempts = data["attempts"]
            correct = data["correct"]

            if attempts == 0:
                mastery = 0
            else:
                mastery = correct / attempts

            state = get_learning_state(mastery)

            if state == "strong":

                strong_concepts += 1
                icon = "🟢"

            elif state == "learning":

                learning_concepts += 1
                icon = "🟡"

            else:

                weak_concepts += 1
                icon = "🔴"

            print(
                f"{icon} {concept:<25} "
                f"{mastery * 100:>5.0f}% "
                f"({correct}/{attempts}) "
                f"[{state}]"
            )

    print("\n" + "-" * 60)

    print(f"Total concepts : {total_concepts}")
    print(f"🟢 Strong      : {strong_concepts}")
    print(f"🟡 Learning    : {learning_concepts}")
    print(f"🔴 Weak        : {weak_concepts}")


def record_progress(
    tutor_response,
    student_answer,
    evaluation
):
    """
    Save the student's learning progress based on
    topic and concept rather than the exact question.
    """

    progress = load_progress()

    topic = tutor_response.topic
    concept = tutor_response.concept

    # --------------------------------------------------------
    # Create topic if it doesn't exist
    # --------------------------------------------------------

    if topic not in progress:
        progress[topic] = {}

    # --------------------------------------------------------
    # Create concept if it doesn't exist
    # --------------------------------------------------------

    if concept not in progress[topic]:

        progress[topic][concept] = {
            "attempts": 0,
            "correct": 0,
            "incorrect": 0,
            "history": []
        }

    concept_data = progress[topic][concept]

    # --------------------------------------------------------
    # Update counters
    # --------------------------------------------------------

    concept_data["attempts"] += 1

    if evaluation.correct:

        concept_data["correct"] += 1

    else:

        concept_data["incorrect"] += 1

    # --------------------------------------------------------
    # Save individual attempt
    # --------------------------------------------------------

    concept_data["history"].append({
        "question": tutor_response.quiz_question,
        "student_answer": student_answer,
        "correct": evaluation.correct
    })

    # --------------------------------------------------------
    # Save to file
    # --------------------------------------------------------

    save_progress(progress)


