# 6. EVALUATE STUDENT ANSWER
# ============================================================

def evaluate_answer(
    tutor_response,
    student_answer
):
    """
    Dynamically evaluate the student's answer.

    There are NO hardcoded questions or answers.
    """

    prompt = f"""
You are a strict but fair Data Science tutor.

==================================================
QUIZ QUESTION
==================================================

{tutor_response.quiz_question}

==================================================
EXPECTED ANSWER
==================================================

{tutor_response.expected_answer}

==================================================
EXPECTED ANSWER EXPLANATION
==================================================

{tutor_response.quiz_explanation}

==================================================
STUDENT ANSWER
==================================================

{student_answer}

==================================================
EVALUATION RULES
==================================================

1. Judge the meaning of the student's answer,
   not the exact wording.

2. A short answer can be completely correct.

3. Minor spelling or grammar mistakes should
   not make an answer incorrect.

4. If the student's answer communicates the same
   concept as the expected answer, mark it correct.

5. If the student's answer contradicts the expected
   answer, mark it incorrect.

6. If the answer is missing an important part that
   changes the meaning, mark it incorrect.

7. Give short, clear and encouraging feedback.

8. Do not invent information that is not contained
   in the expected answer or its explanation.
"""

    try:

        return generate_with_retry(
            prompt,
            Evaluation
        )

    except Exception as e:

        print(
            "\n❌ Gemini could not evaluate the answer."
        )

        print("Reason:", e)

        return None


