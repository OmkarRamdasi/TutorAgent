def generate_tutor_response(
    question,
    retrieved_chunks,
    concept_identification,
    concept_history,
    mastery,
    learning_state
):
    """
    Generate a structured lesson and quiz using:

    1. Course material
    2. Student question
    3. Identified concept
    4. Student's previous learning history
    5. Student mastery
    6. Learning state
    """

    context = "\n\n".join(
        retrieved_chunks
    )

    # --------------------------------------------------------
    # Convert memory into readable text
    # --------------------------------------------------------

    if concept_history is None:

        memory_context = """
The student has no previous learning history
for this concept.

Treat this as a new concept for the student.
"""

    else:

        memory_context = f"""
The student has studied this concept before.

Previous learning history:

{json.dumps(
    concept_history,
    indent=4
)}

Use this information to personalize the teaching.
"""

    prompt = f"""
You are a Data Science tutor.

Your job is to teach the student using ONLY the
course material provided below.

==================================================
COURSE MATERIAL
==================================================

{context}

==================================================
STUDENT QUESTION
==================================================

{question}

==================================================
IDENTIFIED TOPIC
==================================================

{concept_identification.topic}

==================================================
IDENTIFIED CONCEPT
==================================================

{concept_identification.concept}

==================================================
STUDENT MEMORY
==================================================

{memory_context}

==================================================
STUDENT MASTERY
==================================================

Mastery: {mastery * 100:.0f}%

Learning state: {learning_state}

==================================================
TEACHING RULES
==================================================

1. Teach ONLY using the provided course material.

2. Use the identified topic and concept.

3. Explain the concept as if teaching a 5-year-old.

4. Start with a very simple explanation.

5. Give a simple real-world analogy.

6. Then explain the technical meaning.

7. Give one simple example.

8. Create ONE short quiz question.

9. The quiz must test the concept being taught.

10. The quiz must be based ONLY on the course material.

11. Provide the correct expected answer.

12. Explain why the expected answer is correct.

13. Do not invent information outside the course material.

14. If the course material does not contain enough
    information, clearly say that the information
    was not found.

15. Keep the explanation beginner-friendly.

==================================================
PERSONALIZATION RULES
==================================================

If the student has previous history:

- Use it to understand their previous performance.
- Do not repeat exactly the same quiz question.
- If they previously answered correctly, you may
  make the explanation or quiz slightly more challenging.
- If they previously answered incorrectly, explain
  the concept more carefully and use another analogy.
- Do not assume mastery from a single correct answer.
- Do not invent knowledge about the student.

The student's memory is context, not course material.
Course material is always the source of truth.

==================================================
ADAPTIVE TEACHING RULES
==================================================

If the learning state is "weak":

- Explain the concept more slowly.
- Use a very simple analogy.
- Focus on the fundamental idea.
- Create an easier quiz question.
- Do not assume the student understands the concept.

If the learning state is "learning":

- Give a normal beginner-friendly explanation.
- Use one analogy and one example.
- Create a moderate quiz question.
- Reinforce the important parts of the concept.

If the learning state is "strong":

- Keep the explanation concise.
- Avoid repeating everything from previous lessons.
- Give a slightly more challenging quiz question.
- Test whether the student can apply the concept.
- Do not assume complete mastery from the score alone.
"""

    try:

        return generate_with_retry(
            prompt,
            TutorResponse
        )

    except Exception as e:

        print(
            "\n❌ Gemini could not generate the lesson."
        )

        print("Reason:", e)

        return None


