# RELIABLE GEMINI GENERATION
# ============================================================

def generate_with_retry(
    prompt,
    response_schema,
    max_retries=3
):
    """
    Reliable Gemini generation.

    Strategy:

    Primary model
        ↓
    Retry temporary errors
        ↓
    If still unavailable
        ↓
    Fallback model
        ↓
    Retry fallback
    """

    models = [
        PRIMARY_MODEL,
        FALLBACK_MODEL
    ]

    for model_index, model in enumerate(models):

        for attempt in range(max_retries):

            try:

                print(
                    f"\n🤖 Using {model} "
                    f"(attempt {attempt + 1}/{max_retries})"
                )

                response = client.models.generate_content(
                    model=model,
                    contents=prompt,
                    config={
                        "response_mime_type": "application/json",
                        "response_schema": response_schema,
                    },
                )

                return response.parsed

            except Exception as e:

                error_text = str(e)

                # ------------------------------------------------
                # Temporary errors
                # ------------------------------------------------

                is_temporary_error = (
                    "503" in error_text
                    or "UNAVAILABLE" in error_text
                    or "500" in error_text
                    or "INTERNAL" in error_text
                    or "504" in error_text
                    or "DEADLINE_EXCEEDED" in error_text
                )

                # ------------------------------------------------
                # Do not retry permanent errors
                # ------------------------------------------------

                if not is_temporary_error:
                    raise

                # ------------------------------------------------
                # Last attempt for current model
                # ------------------------------------------------

                if attempt == max_retries - 1:

                    print(
                        f"\n⚠️ {model} is unavailable "
                        f"after {max_retries} attempts."
                    )

                    break

                # ------------------------------------------------
                # Exponential backoff + jitter
                # ------------------------------------------------

                base_delay = 2 ** attempt

                jitter = random.uniform(
                    0,
                    1
                )

                wait_time = base_delay + jitter

                print(
                    f"⚠️ Temporary Gemini error."
                    f" Retrying in {wait_time:.1f} seconds..."
                )

                time.sleep(wait_time)

        # --------------------------------------------------------
        # Move to fallback model
        # --------------------------------------------------------

        if model_index < len(models) - 1:

            print(
                f"\n🔄 Switching from "
                f"{model} → {models[model_index + 1]}"
            )

    raise RuntimeError(
        "Gemini is temporarily unavailable on both "
        "the primary and fallback models."
    )


