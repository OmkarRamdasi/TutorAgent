def detect_intent(question):
    """
    Understand what the student wants to do.

    Possible intents:
    - teach
    - practice
    - progress
    """

    prompt = f"""
You are the intent classifier for a Data Science tutor.

Understand what the student wants.

==================================================
STUDENT REQUEST
==================================================

{question}

==================================================
POSSIBLE INTENTS
==================================================

teach
    The student wants to learn or understand
    a Data Science concept.

practice
    The student wants questions or practice
    on a Data Science concept.

progress
    The student wants to see their learning
    progress, mastery, strengths, or weaknesses.

==================================================
RULES
==================================================

1. Return exactly one intent.

2. If the student asks to explain, learn,
   understand, or teach a concept:
   intent = "teach"

3. If the student asks for questions,
   practice, testing, or a quiz:
   intent = "practice"

4. If the student asks about their progress,
   mastery, performance, strengths, or weaknesses:
   intent = "progress"

5. Extract the concept if one is mentioned.

6. If no concept is relevant, return an
   empty string.

7. Do not invent a concept.
"""

    try:

        return generate_with_retry(
            prompt,
            IntentDetection
        )

    except Exception as e:

        print(
            "\n❌ Could not understand the request."
        )

        print("Reason:", e)

        return None


