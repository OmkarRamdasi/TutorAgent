# ============================================================

def practice(concept):
    """
    Practice a specific Data Science concept.
    """

    # --------------------------------------------------------
    # STEP 1: RETRIEVE COURSE MATERIAL
    # --------------------------------------------------------

    retrieved_chunks = retrieve(
        concept
    )

    # --------------------------------------------------------
    # STEP 2: IDENTIFY TOPIC + CONCEPT
    # --------------------------------------------------------

    concept_identification = identify_concept(
        concept,
        retrieved_chunks
    )

    if concept_identification is None:
        return

    actual_topic = (
        concept_identification.topic
    )

    actual_concept = (
        concept_identification.concept
    )

    # --------------------------------------------------------
    # STEP 3: READ STUDENT MEMORY
    # --------------------------------------------------------

    concept_history = get_concept_history(
        actual_topic,
        actual_concept
    )

    # --------------------------------------------------------
    # STEP 4: CALCULATE MASTERY
    # --------------------------------------------------------

    mastery = calculate_mastery(
        actual_topic,
        actual_concept
    )

    learning_state = get_learning_state(
        mastery
    )

    # --------------------------------------------------------
    # STEP 5: DISPLAY STUDENT STATUS
    # --------------------------------------------------------

    print("\n" + "=" * 60)
    print("🧠 PRACTICE MODE")
    print("=" * 60)

    print("\nTopic:")
    print(actual_topic)

    print("\nConcept:")
    print(actual_concept)

    print(
        f"\n📊 Mastery: "
        f"{mastery * 100:.0f}%"
    )

    print(
        f"📚 Learning state: "
        f"{learning_state}"
    )

    # --------------------------------------------------------
    # STEP 6: GENERATE PRACTICE QUESTION
    # --------------------------------------------------------

    practice_question = generate_practice_question(
        actual_concept,
        retrieved_chunks,
        concept_history,
        mastery,
        learning_state
    )

    if practice_question is None:
        return

    # --------------------------------------------------------
    # STEP 7: DISPLAY QUESTION
    # --------------------------------------------------------

    print("\n" + "-" * 60)
    print("📝 PRACTICE QUESTION")
    print("-" * 60)

    print(
        practice_question.question
    )

    # --------------------------------------------------------
    # STEP 8: GET STUDENT ANSWER
    # --------------------------------------------------------

    student_answer = input(
        "\nYour answer: "
    )

    # --------------------------------------------------------
    # STEP 9: EVALUATE ANSWER
    # --------------------------------------------------------

    evaluation_prompt = f"""
You are a strict but fair Data Science tutor.

QUESTION:
{practice_question.question}

EXPECTED ANSWER:
{practice_question.expected_answer}

EXPECTED ANSWER EXPLANATION:
{practice_question.explanation}

STUDENT ANSWER:
{student_answer}

Evaluate the student's answer.

Rules:

1. Judge meaning, not exact wording.

2. Minor spelling or grammar mistakes
   should not make an answer incorrect.

3. If the student communicates the same
   meaning as the expected answer, mark
   it correct.

4. If the answer contradicts the expected
   answer, mark it incorrect.

5. Give short and encouraging feedback.

6. Do not introduce information outside
   the expected answer and explanation.
"""

    try:

        evaluation = generate_with_retry(
            evaluation_prompt,
            Evaluation
        )

    except Exception as e:

        print(
            "\n❌ Gemini could not evaluate "
            "the practice answer."
        )

        print("Reason:", e)

        return

    if evaluation is None:
        return

    # --------------------------------------------------------
    # STEP 10: SAVE PROGRESS
    # --------------------------------------------------------

    tutor_response = TutorResponse(
        topic=actual_topic,
        concept=actual_concept,
        lesson="",
        quiz_question=practice_question.question,
        expected_answer=practice_question.expected_answer,
        quiz_explanation=practice_question.explanation
    )

    record_progress(
        tutor_response,
        student_answer,
        evaluation
    )

    # --------------------------------------------------------
    # STEP 11: DISPLAY RESULT
    # --------------------------------------------------------

    print("\n" + "=" * 60)
    print("🎯 PRACTICE RESULT")
    print("=" * 60)

    if evaluation.correct:

        print("\n✅ CORRECT!")
        print(evaluation.feedback)

    else:

        print("\n❌ NOT QUITE")
        print(evaluation.feedback)

        print("\nCorrect answer:")
        print(
            practice_question.expected_answer
        )

        print("\nWhy:")
        print(
            practice_question.explanation
        )

    # --------------------------------------------------------
    # STEP 12: SHOW UPDATED MASTERY
    # --------------------------------------------------------

    new_mastery = calculate_mastery(
        actual_topic,
        actual_concept
    )

    new_state = get_learning_state(
        new_mastery
    )

    print("\n📊 UPDATED PROGRESS")

    print(
        f"Mastery: "
        f"{new_mastery * 100:.0f}%"
    )

    print(
        f"Learning state: "
        f"{new_state}"
    )


